###############################################################################
#  99 — SOFTWARE ENVIRONMENT RECORD
#
#  WHY
#  The pipeline depends on mice, missRanger, imputeTS and forecast. These
#  packages evolve: missRanger has changed defaults between major versions,
#  imputeTS has changed the behaviour of na_kalman. Without a record of the
#  versions, a different result in two years is indistinguishable from a bug.
#  The code would be AVAILABLE but not REPRODUCIBLE -- and that is exactly
#  what a methodological reviewer tests.
#
#  Ideally run it in the SAME R session as the pipeline, so that the list of
#  loaded packages is complete.
#  Produces: docs/ENVIRONMENT.md and docs/package_versions.csv
###############################################################################

dir.create("docs", showWarnings = FALSE)

PKGS <- c("tidyverse", "dplyr", "tidyr", "readr", "ggplot2", "purrr",
          "lubridate", "mice", "VIM", "missRanger", "ranger", "imputeTS",
          "forecast", "PMCMRplus", "tictoc", "sf", "openxlsx", "ggrepel",
          "spdep", "httr")

## ---------------------------------------------------------------- Versions
row_for <- function(p) {
  v <- tryCatch(as.character(utils::packageVersion(p)),
                error = function(e) NA_character_)
  data.frame(package = p, version = v, installed = !is.na(v),
             stringsAsFactors = FALSE)
}
vers <- do.call(rbind, lapply(PKGS, row_for))

# A package used but not declared above would go unnoticed, so we ALSO list
# everything attached at the time of the call.
attached <- names(utils::sessionInfo()$otherPkgs)
extra    <- setdiff(attached, PKGS)
if (length(extra)) vers <- rbind(vers, do.call(rbind, lapply(extra, row_for)))

vers <- vers[order(!vers$installed, vers$package), ]
write.csv(vers, "docs/package_versions.csv", row.names = FALSE)

## ------------------------------------------------------------ ENVIRONMENT.md
si  <- utils::sessionInfo()
con <- file("docs/ENVIRONMENT.md", open = "w", encoding = "UTF-8")
wr  <- function(...) cat(..., "\n", sep = "", file = con)

wr("# Software environment")
wr("")
wr("Generated by `R/99_session_info.R` on ",
   format(Sys.time(), "%Y-%m-%d %H:%M:%S %Z"), ".")
wr("This file accompanies the code deposit and serves as the reproducibility ",
   "reference.")
wr("")
wr("## System")
wr("")
wr("| Item | Value |")
wr("|---|---|")
wr("| R version | ", si$R.version$version.string, " |")
wr("| Platform | ", si$platform, " |")
wr("| Running under | ", si$running, " |")
wr("| Locale | ", gsub(";", " ; ", Sys.getlocale()), " |")
wr("| BLAS | ", if (!is.null(si$BLAS)) si$BLAS else "not reported", " |")
wr("")
wr("## Package versions")
wr("")
wr("| Package | Version |")
wr("|---|---|")
for (i in seq_len(nrow(vers)))
  wr("| ", vers$package[i], " | ",
     if (vers$installed[i]) vers$version[i] else "**NOT INSTALLED**", " |")
wr("")

absent <- vers$package[!vers$installed]
if (length(absent)) {
  wr("> **Packages absent from this machine**: ", paste(absent, collapse = ", "), ".")
  wr("> This only matters if they are needed by the scripts you run")
  wr("> (`sf` and `spdep` are used only by the map, `httr` only by its download).")
  wr("")
}

wr("## Full sessionInfo()")
wr("")
wr("```")
writeLines(utils::capture.output(print(si)), con = con)
wr("```")
wr("")
wr("## Note on reproducibility")
wr("")
wr("This file DOCUMENTS the environment but does not allow it to be RESTORED.")
wr("For strict reproducibility, initialise `renv` at the project root:")
wr("")
wr("```r")
wr("renv::init()      # once")
wr("renv::snapshot()  # after every change of packages")
wr("```")
wr("")
wr("The resulting `renv.lock` lets a third party restore exactly the same")
wr("versions with `renv::restore()`. It should be committed to the repository.")
close(con)

cat("Written: docs/ENVIRONMENT.md and docs/package_versions.csv\n\n")
cat(sprintf("  R         : %s\n", si$R.version$version.string))
cat(sprintf("  Platform  : %s\n", si$platform))
cat(sprintf("  Packages  : %d listed, %d installed\n", nrow(vers), sum(vers$installed)))
if (length(absent)) cat("  Absent    : ", paste(absent, collapse = ", "), "\n", sep = "")
cat("\nRemember to commit these two files to the GitHub repository.\n")
